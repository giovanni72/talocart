// Runs only inside the demo suite's isolated schema; never changes application products.
const assert = require('node:assert/strict');
const path = require('node:path');
module.exports = async ({page, query, origin, js, output, name}) => {
  const classId = String((await query('SELECT t.id FROM tax_classes t JOIN tax_rates r ON r.id=t.rate_id WHERE t.active AND r.active ORDER BY t.id LIMIT 1')).rows[0].id);
  const section = async label => page.getByRole(js?'tab':'link',{name:label,exact:true}).click();
  await page.goto(origin+'/admin/catalog/products/new');
  await page.getByLabel('Nome del prodotto',{exact:true}).fill('Senza categoria');
  await page.getByLabel('Modello',{exact:true}).fill('OPTIONAL-CATEGORY-1');
  await page.getByLabel('Slug',{exact:true}).fill('optional-category-1');
  await section('Prezzo e disponibilità');
  await page.getByLabel('Prezzo unitario (€)',{exact:true}).fill('12,34');
  await page.getByLabel('Classe fiscale',{exact:true}).selectOption(classId);
  await section('Organizzazione');
  assert.equal(await page.getByLabel('Categoria (facoltativa)',{exact:true}).inputValue(),'');
  assert.equal(await page.locator('#product-category option').first().innerText(),'Nessuna categoria');
  await page.getByLabel('Stato del prodotto',{exact:true}).selectOption('published');
  await page.getByRole('button',{name:'Crea prodotto',exact:true}).click();
  await page.waitForURL(url=>url.searchParams.get('saved')==='1');
  await page.getByRole('status').filter({hasText:'Prodotto salvato.'}).waitFor();
  const {rows:[created]} = await query("SELECT id,status,category_id FROM catalog_products WHERE model='OPTIONAL-CATEGORY-1'");
  assert.equal(created.status,'published'); assert.equal(created.category_id,null);
  await page.screenshot({path:path.join(output,`optional-category-form-${name}.png`),fullPage:true});
  await page.goto(origin+'/search/OPTIONAL-CATEGORY-1');
  await page.getByRole('link',{name:/Senza categoria/}).first().click();
  assert.equal(new URL(page.url()).pathname,'/products/optional-category-1');
  assert.equal((await page.request.get(origin+'/products/optional-category-1')).status(),200);
  await page.screenshot({path:path.join(output,`optional-category-public-${name}.png`),fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  const category = (await query('SELECT slug FROM catalog_categories WHERE active ORDER BY id LIMIT 1')).rows[0].slug;
  await page.goto(origin+'/catalog/'+encodeURIComponent(category));
  assert.equal(await page.locator('a[href="/products/optional-category-1"]').count(),0);
  // A second uncategorized draft is published with the first product through the same bulk UI.
  await query("INSERT INTO catalog_products(name,model,slug,price_cents,tax_class_id) VALUES('Senza categoria due','OPTIONAL-CATEGORY-2','optional-category-2',1000,$1)",[classId]);
  await page.goto(origin+'/admin/catalog/products?model=OPTIONAL-CATEGORY');
  const rows=page.locator('.product-row-select'); assert.equal(await rows.count(),2);
  await rows.first().check(); await rows.nth(1).check();
  await page.getByRole('button',{name:'Azioni multiple',exact:true}).click();
  await page.getByRole('checkbox',{name:'Pubblica prodotto',exact:true}).check();
  await page.getByRole('checkbox',{name:'Confermo le azioni su tutti i 2 prodotti selezionati',exact:true}).check();
  await page.getByRole('button',{name:'Applica azioni',exact:true}).click();
  await page.waitForURL(url=>url.searchParams.get('bulk_status')==='published');
  assert.ok((await query("SELECT status,category_id FROM catalog_products WHERE model LIKE 'OPTIONAL-CATEGORY-%'")).rows.every(p=>p.status==='published' && p.category_id===null));
  assert.equal((await page.request.get(origin+'/products/optional-category-2')).status(),200);
  await page.goto(origin+`/admin/catalog/products/${created.id}?tab=organization`);
  await page.getByRole('button',{name:'Salva prodotto',exact:true}).click();
  await page.waitForURL(url=>url.searchParams.get('saved')==='1');
  assert.equal((await page.request.get(origin+'/products/optional-category-1')).status(),200,'An edit preserves publication without a category');
  await query("DELETE FROM catalog_products WHERE model LIKE 'OPTIONAL-CATEGORY-%'");
};
