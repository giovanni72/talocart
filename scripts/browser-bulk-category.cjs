const assert = require('node:assert/strict');
const path = require('node:path');
// Fixtures belong to the demo suite's isolated schema, including its published products.
module.exports = async ({page,query,origin,js,output,name}) => {
  const root=(await query("INSERT INTO catalog_categories(name,slug,active) VALUES('Bulk tree <root>','bulk-tree-root',false) RETURNING id")).rows[0].id;
  const child=(await query("INSERT INTO catalog_categories(name,slug,parent_id) VALUES('Child','bulk-tree-child',$1) RETURNING id",[root])).rows[0].id;
  const leaf=(await query("INSERT INTO catalog_categories(name,slug,parent_id) VALUES('Leaf','bulk-tree-leaf',$1) RETURNING id",[child])).rows[0].id;
  const inactive=(await query("INSERT INTO catalog_categories(name,slug,active) VALUES('Bulk inactive','bulk-tree-inactive',false) RETURNING id")).rows[0].id;
  const classId=(await query('SELECT t.id FROM tax_classes t JOIN tax_rates r ON r.id=t.rate_id WHERE t.active AND r.active ORDER BY t.id LIMIT 1')).rows[0].id;
  const old=(await query('SELECT id FROM catalog_categories WHERE active ORDER BY id LIMIT 1')).rows[0].id;
  const {rows:products}=await query("INSERT INTO catalog_products(name,model,slug,price_cents,category_id,tax_class_id,status) SELECT 'Bulk category '||i,'BULK-CATEGORY-'||i,'bulk-category-'||i,1234,$1,$2,CASE WHEN i=1 THEN 'published' ELSE 'draft' END FROM generate_series(1,3) i RETURNING id",[old,classId]);
  const snapshot = async () => (await query("SELECT (to_jsonb(p)-'category_id')::text AS row FROM catalog_products p WHERE model LIKE 'BULK-CATEGORY-%' ORDER BY id")).rows;
  const before=await snapshot();
  const target=origin+'/admin/catalog/products?model=BULK-CATEGORY&sort=id&dir=asc&per_page=10';
  const open=async () => {
    await page.goto(target);
    const rows=page.locator('.product-row-select');
    await rows.first().focus(); await page.keyboard.press('Space'); await rows.nth(1).check();
    await page.getByRole('button',{name:'Azioni multiple',exact:true}).click();
    assert.equal(await page.locator('.product-table').count(),0);
    await page.getByText('2 prodotti selezionati.',{exact:true}).waitFor();
    const panel=page.locator('#bulk-category-panel');
    assert.equal(await panel.isVisible(),!js);
    await page.getByRole('checkbox',{name:'Assegna categoria',exact:true}).check();
    assert.equal(await panel.isVisible(),true);
    assert.equal(await page.getByRole('radio',{name:'Bulk tree <root> (disattivata)',exact:true}).count(),1);
    const leafRadio=page.getByRole('radio',{name:'Bulk tree <root> / Child / Leaf',exact:true});
    await leafRadio.focus(); await page.keyboard.press('Space');
    assert.equal(await leafRadio.isChecked(),true);
    const nesting=await leafRadio.evaluate(radio => {
      const li=radio.closest('li');const parent=li.parentElement.closest('li');
      return [parent.querySelector('input').value,parent.parentElement.closest('li').querySelector('input').value];
    });
    assert.deepEqual(nesting,[String(child),String(root)]);
  };
  await open();
  await page.screenshot({path:path.join(output,`bulk-category-${name}.png`),fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Category tree stays within the viewport');
  await page.getByRole('link',{name:'Annulla',exact:true}).click();
  assert.ok((await query("SELECT category_id FROM catalog_products WHERE model LIKE 'BULK-CATEGORY-%'")).rows.every(p=>p.category_id===old));
  await open();
  await page.getByRole('checkbox',{name:'Confermo le azioni su tutti i 2 prodotti selezionati',exact:true}).check();
  await page.getByRole('button',{name:'Applica azioni',exact:true}).click();
  await page.waitForURL(url=>url.searchParams.get('bulk_category')==='1');
  await page.getByRole('status').filter({hasText:'Categoria assegnata ai prodotti selezionati.'}).waitFor();
  assert.equal(new URL(page.url()).searchParams.get('model'),'BULK-CATEGORY');
  assert.equal(new URL(page.url()).searchParams.get('per_page'),'10');
  assert.equal(await page.locator('.product-row-select:checked').count(),0);
  const after=(await query("SELECT id,status,category_id FROM catalog_products WHERE model LIKE 'BULK-CATEGORY-%' ORDER BY id")).rows;
  assert.deepEqual(after.map(p=>p.category_id),[leaf,leaf,old]);
  assert.deepEqual(after.map(p=>p.status),['published','draft','draft']);
  assert.deepEqual(await snapshot(),before,'Only category_id changes');
  assert.equal((await page.request.get(origin+'/products/bulk-category-1')).status(),200,'Published product remains published after assignment');
  assert.equal((await page.request.get(origin+'/products/bulk-category-2')).status(),404,'Draft remains a draft');
  // Combine publication and assignment. Native checkboxes submit both actions even without JS.
  await open();
  await page.getByRole('checkbox',{name:'Pubblica prodotto',exact:true}).check();
  assert.equal(await page.getByRole('checkbox',{name:'Assegna categoria',exact:true}).isChecked(),true);
  if (js) {
    await page.getByRole('checkbox',{name:'Bozza prodotto',exact:true}).check();
    assert.equal(await page.getByRole('checkbox',{name:'Pubblica prodotto',exact:true}).isChecked(),false);
    await page.getByRole('checkbox',{name:'Elimina',exact:true}).check();
    assert.equal(await page.getByRole('checkbox',{name:'Assegna categoria',exact:true}).isChecked(),false);
    assert.equal(await page.getByRole('checkbox',{name:'Bozza prodotto',exact:true}).isChecked(),false);
    await page.getByRole('checkbox',{name:'Pubblica prodotto',exact:true}).check();
    await page.getByRole('checkbox',{name:'Assegna categoria',exact:true}).check();
    assert.equal(await page.getByRole('checkbox',{name:'Elimina',exact:true}).isChecked(),false);
  }
  await page.getByRole('radio',{name:'Bulk tree <root> / Child',exact:true}).check();
  await page.screenshot({path:path.join(output,`bulk-combined-${name}.png`),fullPage:true});
  await page.getByRole('checkbox',{name:'Confermo le azioni su tutti i 2 prodotti selezionati',exact:true}).check();
  await page.getByRole('button',{name:'Applica azioni',exact:true}).click();
  await page.waitForURL(url=>url.searchParams.get('bulk_applied')==='1');
  await page.getByRole('status').filter({hasText:'Azioni applicate ai prodotti selezionati.'}).waitFor();
  assert.deepEqual((await query("SELECT status,category_id FROM catalog_products WHERE model LIKE 'BULK-CATEGORY-%' ORDER BY id")).rows,[{status:'published',category_id:child},{status:'published',category_id:child},{status:'draft',category_id:old}]);
  assert.equal((await page.request.get(origin+'/products/bulk-category-2')).status(),200);
  await open();
  await page.getByRole('checkbox',{name:'Pubblica prodotto',exact:true}).check();
  await page.getByRole('radio',{name:'Bulk inactive (disattivata)',exact:true}).check();
  await page.getByRole('checkbox',{name:'Confermo le azioni su tutti i 2 prodotti selezionati',exact:true}).check();
  const rejected=page.waitForResponse(r=>r.request().method()==='POST' && r.url().endsWith('/bulk/apply'));
  await page.getByRole('button',{name:'Applica azioni',exact:true}).click(); assert.equal((await rejected).status(),409);
  await page.getByRole('alert').waitFor();
  assert.equal(await page.getByRole('checkbox',{name:'Assegna categoria',exact:true}).isChecked(),true);
  assert.equal(await page.getByRole('checkbox',{name:'Pubblica prodotto',exact:true}).isChecked(),true);
  assert.equal(await page.getByRole('radio',{name:'Bulk inactive (disattivata)',exact:true}).isChecked(),true);
  assert.equal(await page.getByRole('checkbox',{name:'Confermo le azioni su tutti i 2 prodotti selezionati',exact:true}).isChecked(),false);
  assert.deepEqual((await query('SELECT category_id FROM catalog_products WHERE id=ANY($1::bigint[]) ORDER BY id',[products.slice(0,2).map(p=>p.id)])).rows.map(p=>p.category_id),[child,child]);
  await query("DELETE FROM catalog_products WHERE model LIKE 'BULK-CATEGORY-%'");
  for (const id of [leaf,child,root,inactive]) await query('DELETE FROM catalog_categories WHERE id=$1',[id]);
};
